"""Generate the Portal Pad block, its 16 colour textures, the item icon and the script's colour table.

COLORS below is the single source of truth for the pad colours (one per dye). A pad's colour is
the block state mymod:color (an index into COLORS; 0 = purple, what every new pad starts as).
Pads of the same colour are linked; see scripts/portal.js.

Outputs:
  <bp>/blocks/portal_pad.json                       the block, one permutation per colour
  <bp>/scripts/portal_colors.js                     COLORS for the script (names, dyes, particle colours)
  <rp>/textures/blocks/portal_pad_<color>.png       16x16 swirl, one per colour
  <rp>/textures/items/portal_pad.png                16x16 item icon

Run standalone:  python tools/gen_portal.py
"""

from __future__ import annotations

import json
import math
import sys
from dataclasses import dataclass

from PIL import Image

from common import BuildError, load_config, rel, write_json, write_text

PAD_ID = "mymod:portal_pad"
STATE = "mymod:color"
GEOMETRY_ID = "geometry.mymod.portal_pad"
ICON_TEXTURE = "textures/items/portal_pad"


@dataclass(frozen=True)
class Color:
    key: str
    name: str
    rgb: tuple[int, int, int]
    dyes: tuple[str, ...]


# Index = block state value. Purple first: it's the default, so any two new pads are linked.
COLORS = [
    Color("purple", "Purple", (150, 60, 220), ("minecraft:purple_dye",)),
    Color("white", "White", (236, 236, 236), ("minecraft:white_dye", "minecraft:bone_meal")),
    Color("orange", "Orange", (249, 128, 29), ("minecraft:orange_dye",)),
    Color("magenta", "Magenta", (210, 80, 200), ("minecraft:magenta_dye",)),
    Color("light_blue", "Light Blue", (70, 190, 235), ("minecraft:light_blue_dye",)),
    Color("yellow", "Yellow", (254, 216, 61), ("minecraft:yellow_dye",)),
    Color("lime", "Lime", (128, 210, 31), ("minecraft:lime_dye",)),
    Color("pink", "Pink", (243, 139, 170), ("minecraft:pink_dye",)),
    Color("gray", "Gray", (100, 108, 112), ("minecraft:gray_dye",)),
    Color("light_gray", "Light Gray", (170, 170, 164), ("minecraft:light_gray_dye",)),
    Color("cyan", "Cyan", (22, 170, 170), ("minecraft:cyan_dye",)),
    Color("blue", "Blue", (60, 80, 220), ("minecraft:blue_dye", "minecraft:lapis_lazuli")),
    Color("brown", "Brown", (140, 90, 52), ("minecraft:brown_dye", "minecraft:cocoa_beans")),
    Color("green", "Green", (80, 140, 30), ("minecraft:green_dye",)),
    Color("red", "Red", (210, 50, 40), ("minecraft:red_dye",)),
    Color("black", "Black", (40, 36, 48), ("minecraft:black_dye", "minecraft:ink_sac")),
]


def texture_path(c: Color) -> str:
    return f"textures/blocks/portal_pad_{c.key}"


def atlas_key(c: Color) -> str:
    return f"mymod_portal_pad_{c.key}"


ALL_TEXTURES = [texture_path(c) for c in COLORS] + [ICON_TEXTURE]


def block() -> dict:
    perms = [
        {
            "condition": f"q.block_state('{STATE}') == {i}",
            "components": {
                "minecraft:material_instances": {
                    "*": {"texture": atlas_key(c), "render_method": "alpha_test"},
                },
                "minecraft:map_color": "#{:02x}{:02x}{:02x}".format(*c.rgb),
            },
        }
        for i, c in enumerate(COLORS)
    ]
    return {
        "format_version": "1.26.50",
        "minecraft:block": {
            "description": {
                "identifier": PAD_ID,
                "menu_category": {"category": "equipment"},
                # integer states must be a min/max range (a plain list must be strings)
                "states": {STATE: {"values": {"min": 0, "max": len(COLORS) - 1}}},
            },
            "components": {
                "minecraft:geometry": GEOMETRY_ID,
                "minecraft:material_instances": {
                    "*": {"texture": atlas_key(COLORS[0]), "render_method": "alpha_test"},
                },
                "minecraft:collision_box": {"origin": [-8, 0, -8], "size": [16, 1, 16]},
                "minecraft:selection_box": {"origin": [-8, 0, -8], "size": [16, 1, 16]},
                "minecraft:placement_filter": {"conditions": [{"allowed_faces": ["up"]}]},
                "minecraft:destructible_by_mining": {"seconds_to_destroy": 0.5},
                "minecraft:destructible_by_explosion": False,
                "minecraft:light_emission": 10,
                "minecraft:light_dampening": 0,
            },
            "permutations": perms,
        },
    }


def colors_js() -> str:
    rows = [
        {"key": c.key, "name": c.name, "rgb": [round(v / 255, 3) for v in c.rgb], "dyes": list(c.dyes)} for c in COLORS
    ]
    body = ",\n".join(f"  {json.dumps(r)}" for r in rows)
    return (
        "// GENERATED by tools/gen_portal.py - do not edit. Index = the pad's mymod:color block state.\n"
        f'export const PAD_STATE = "{STATE}";\n'
        f"export const COLORS = [\n{body},\n];\n"
    )


def _mix(a, b, t):
    return tuple(round(x + (y - x) * t) for x, y in zip(a, b, strict=True))


FRAME = (34, 24, 46)
FRAME_LIGHT = (70, 54, 90)


def pad_texture(c: Color) -> Image.Image:
    """Obsidian-like rim around a two-armed swirl in the pad's colour, bright in the middle."""
    im = Image.new("RGBA", (16, 16))
    dark = _mix(c.rgb, (0, 0, 0), 0.55)
    light = _mix(c.rgb, (255, 255, 255), 0.45)
    for y in range(16):
        for x in range(16):
            dx, dy = x - 7.5, y - 7.5
            if max(abs(dx), abs(dy)) > 6.5:
                rgb = FRAME_LIGHT if (x + y) % 5 == 0 else FRAME
            else:
                r = math.hypot(dx, dy)
                swirl = (math.sin(2 * math.atan2(dy, dx) + r * 1.1) + 1) / 2
                rgb = _mix(dark, light, swirl)
                if r < 2:
                    rgb = _mix(rgb, (255, 255, 255), 0.6 - r * 0.25)
            im.putpixel((x, y), (*rgb, 255))
    return im


def icon() -> Image.Image:
    """The purple pad, drawn as a squashed (perspective) ellipse with a rim."""
    pad = pad_texture(COLORS[0])
    im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y in range(4, 13):
        for x in range(16):
            # map the icon's ellipse onto the square texture
            u = x
            v = round((y - 4) * 15 / 8)
            if ((x - 7.5) / 8) ** 2 + ((y - 8.5) / 4.6) ** 2 <= 1:
                im.putpixel((x, y), pad.getpixel((u, v)))
    for x in range(2, 14):  # the pad's front edge
        if im.getpixel((x, 12))[3]:
            im.putpixel((x, 13), (*FRAME, 255))
    return im


def generate_portal(verbose: bool = True) -> None:
    _, paths = load_config()
    blk = paths.bp / "blocks/portal_pad.json"
    write_json(blk, block())
    js = paths.bp / "scripts/portal_colors.js"
    write_text(js, colors_js())
    written = [blk, js]
    images = [(texture_path(c), pad_texture(c)) for c in COLORS] + [(ICON_TEXTURE, icon())]
    for tex, im in images:
        dest = paths.rp / (tex + ".png")
        dest.parent.mkdir(parents=True, exist_ok=True)
        im.save(dest)
        written.append(dest)
    if verbose:
        print(f"  wrote {rel(blk)}, {rel(js)}, {len(COLORS)} pad textures, {rel(written[-1])}")


if __name__ == "__main__":
    try:
        generate_portal()
    except BuildError as e:
        print(f"ERROR: {e}", file=sys.stderr)
        sys.exit(1)
