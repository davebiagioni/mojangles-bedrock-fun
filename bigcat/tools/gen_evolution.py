# 16x16 icon. s/S/d = stone light/mid/dark, c/C/W = crystal violet/deep/white glint.
STONE = [
    "................",
    "................",
    "......ssss......",
    "....ssSSSSss....",
    "...sSSSCcSSSd...",
    "...sSSCcWcSSd...",
    "..sSSCcWccCSSd..",
    "..sSSCcccccSSd..",
    "..sSSSCcccCSSd..",
    "..sSSSSCcCSSdd..",
    "...sSSSSCSSSd...",
    "...sSSSSSSSdd...",
    "....ddSSSSdd....",
    "......dddd......",
    "................",
    "................",
]
STONE_COLORS = {
    "s": (168, 164, 172, 255),
    "S": (122, 118, 130, 255),
    "d": (74, 70, 84, 255),
    "c": (196, 120, 255, 255),
    "C": (124, 52, 196, 255),
    "W": (250, 236, 255, 255),
}


def stone_icon() -> Image.Image:
    im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(STONE):
        for x, ch in enumerate(row):
            if ch != ".":
                im.putpixel((x, y), STONE_COLORS[ch])
    return im


# Wing UV layout (must match models/entity/big_cat_wings.geo.json): the inner wing is 7x6 px at
# (0, 0), the wing tip 7x8 px at (0, 8). In each, the left column touches the body (or the inner
# wing), the top row is the leading edge and the feathers trail towards the bottom.
INNER = (0, 0, 7, 6)
TIP = (0, 8, 7, 8)
GOLD = (232, 192, 86, 255)
WHITE = (248, 244, 232, 255)
SHADE = (214, 206, 190, 255)


def _feathers(im: Image.Image, box: tuple[int, int, int, int], lengths: list[int]) -> None:
    x0, y0, w, h = box
    for dx in range(w):
        for dy in range(min(lengths[dx], h)):
            if dy == 0:
                c = GOLD
            elif dx % 2 == 1:
                c = SHADE  # every other column a touch darker, so single feathers read
            else:
                c = WHITE
            im.putpixel((x0 + dx, y0 + dy), c)


def wing_texture() -> Image.Image:
    im = Image.new("RGBA", (32, 32), (0, 0, 0, 0))
    _feathers(im, INNER, [6, 6, 5, 6, 5, 6, 5])  # coverts: short ragged trailing edge
    _feathers(im, TIP, [8, 7, 8, 6, 7, 5, 4])  # primaries: longest near the joint, tapering out
    return im


def generate_evolution_textures(verbose: bool = True) -> None:
    _, paths = load_config()
    out = []
    for tex, img in ((STONE_TEXTURE, stone_icon()), (WING_TEXTURE, wing_texture())):
        dest = paths.rp / (tex + ".png")
        dest.parent.mkdir(parents=True, exist_ok=True)
        img.save(dest)
        out.append(rel(dest))
    if verbose:
        print(f"  wrote {', '.join(out)}")


if __name__ == "__main__":
    try:
        generate_evolution_textures()
    except BuildError as e:
        print(f"ERROR: {e}", file=sys.stderr)
        sys.exit(1)
