"""Evolution Stone: the 8 evolution stages, the Big Cat JSON they need, and the textures.

Source of truth for the stages. gen_json.py calls add_evolution() to put the stage property, one
component group per stage and one event per stage into the generated big_cat.json.
scripts/evolution.js has its own copy of the stage names and particles; validate.py checks that
the two lists match.

Outputs (drawn in code, so there is no art file to lose):
  <rp>/textures/items/evolution_stone.png   16x16 item icon: grey stone around a glowing violet crystal
  <rp>/textures/entity/big_cat_wings.png    32x32 feathered wings for stage 8 (models/entity/big_cat_wings.geo.json)

Run standalone:  python tools/gen_evolution.py
"""

from __future__ import annotations

import sys

from PIL import Image

from common import BuildError, load_config, rel

STONE_ID = "mymod:evolution_stone"
STONE_TEXTURE = "textures/items/evolution_stone"
WING_TEXTURE = "textures/entity/big_cat_wings"
ALL_TEXTURES = [STONE_TEXTURE]  # item icons; the wing texture is listed in the client entity

PROPERTY = "mymod:evolution"
GROUP = "mymod:evolution_{n}"
EVENT = "mymod:evolve_{n}"
WING_STAGE = 8

# Unevolved tamed cat for reference: 20 health, 4 attack, 0.3 speed (tools/templates/big_cat.behavior.json).
# name, particle (vanilla, needs no Molang variables), health, attack, speed, knockback resistance, fire immune
STAGES = [
    ("Sprout", "minecraft:villager_happy", 30, 6, 0.31, 0.1, False),
    ("Blossom", "minecraft:cherry_leaves_particle", 40, 8, 0.32, 0.2, False),
    ("Frost", "minecraft:snowflake_particle", 50, 10, 0.33, 0.3, False),
    ("Ember", "minecraft:basic_flame_particle", 60, 12, 0.34, 0.4, True),
    ("Soulfire", "minecraft:blue_flame_particle", 70, 14, 0.35, 0.5, True),
    ("Firefly", "minecraft:firefly_particle", 80, 16, 0.36, 0.6, True),
    ("Arcane", "minecraft:obsidian_glow_dust_particle", 90, 18, 0.38, 0.7, True),
    ("Celestial", "minecraft:endrod", 100, 20, 0.40, 0.8, True),
]
MAX_STAGE = len(STAGES)


def stage_group(n: int) -> dict:
    _, _, health, attack, speed, knockback, fire = STAGES[n - 1]
    g = {
        "minecraft:health": {"value": health, "max": health},
        "minecraft:attack_damage": {"value": attack},
        "minecraft:movement": {"value": speed},
        "minecraft:knockback_resistance": {"value": knockback},
    }
    if fire:
        g["minecraft:fire_immune"] = {}
    return g


def stage_events() -> dict:
    """mymod:evolve_1..8 swap in that stage's group; mymod:evolve_0 removes them all (for testing)."""
    groups = [GROUP.format(n=n) for n in range(1, MAX_STAGE + 1)]
    events = {
        EVENT.format(n=0): {
            "sequence": [
                {"remove": {"component_groups": groups}, "set_property": {PROPERTY: 0}},
                # Removing a group can drop a component another group also defines, so re-apply
                # the tame group for its health.
                {"filters": {"test": "is_tamed"}, "add": {"component_groups": ["minecraft:cat_tame"]}},
            ]
        }
    }
    for n in range(1, MAX_STAGE + 1):
        others = [g for g in groups if g != GROUP.format(n=n)]
        events[EVENT.format(n=n)] = {
            "sequence": [
                {"remove": {"component_groups": others}},
                {"add": {"component_groups": [GROUP.format(n=n)]}, "set_property": {PROPERTY: n}},
            ]
        }
    return events


def add_evolution(entity: dict, where: str = "big_cat template") -> None:
    """Add the stage property, groups and events to a minecraft:entity dict (in place)."""
    new_groups = {GROUP.format(n=n): stage_group(n) for n in range(1, MAX_STAGE + 1)}
    new_events = stage_events()
    if PROPERTY in entity["description"].get("properties", {}):
        raise BuildError(f"{where}: remove '{PROPERTY}' from the template, the build adds it")
    clash = sorted(
        (set(entity.get("component_groups", {})) & set(new_groups)) | (set(entity.get("events", {})) & set(new_events))
    )
    if clash:
        raise BuildError(f"{where}: {clash[:3]} are generated by tools/gen_evolution.py; remove them")
    props = entity["description"].setdefault("properties", {})
    groups = entity.setdefault("component_groups", {})
    events = entity.setdefault("events", {})
    props[PROPERTY] = {"type": "int", "range": [0, MAX_STAGE], "default": 0, "client_sync": True}
    groups.update(new_groups)
    events.update(new_events)


