"""Generate the item, recipe, attachable, item_texture and lang files from tools/gear_config.json.

Run standalone:  python tools/gen_json.py
"""
from __future__ import annotations

import sys

from common import BuildError, load_config, rel, texture_key, write_json, write_text

GLINT = "textures/misc/enchanted_actor_glint"


def item_json(cfg: dict, piece: dict) -> dict:
    mat = cfg["material"]
    return {
        "format_version": cfg["item_format_version"],
        "minecraft:item": {
            "description": {
                "identifier": piece["identifier"],
                "menu_category": {"category": "equipment", "group": piece["group"]},
            },
            "components": {
                "minecraft:icon": {"textures": {"default": texture_key(cfg, piece)}},
                "minecraft:max_stack_size": 1,
                "minecraft:wearable": {"slot": piece["slot"], "protection": piece["protection"]},
                "minecraft:durability": {"max_durability": piece["durability"]},
                "minecraft:enchantable": {"slot": piece["enchant_slot"], "value": mat["enchantability"]},
                "minecraft:repairable": {
                    "repair_items": [
                        {
                            "items": [piece["identifier"]],
                            "repair_amount": "context.other->query.remaining_durability + 0.12 * query.max_durability",
                        },
                        {
                            "items": [mat["repair_item"]],
                            "repair_amount": f"query.max_durability * {mat['repair_fraction']}",
                        },
                    ]
                },
                "minecraft:tags": {"tags": list(mat["tags"])},
            },
        },
    }


def recipe_json(cfg: dict, piece: dict) -> dict:
    r = piece["recipe"]
    return {
        "format_version": cfg["recipe_format_version"],
        "minecraft:recipe_shaped": {
            "description": {"identifier": piece["identifier"]},
            "tags": ["crafting_table"],
            "pattern": list(r["pattern"]),
            "key": {k: {"item": v} for k, v in r["key"].items()},
            "unlock": [{"item": cfg["material"]["repair_item"]}],
            "result": {"item": piece["identifier"]},
        },
    }


def attachables(cfg: dict, paths, piece: dict) -> dict[str, dict]:
    """Two attachables per item, mirroring vanilla (e.g. iron_helmet.json + iron_helmet.player.json):
    a generic one using geometry.humanoid.armor.* (armor stands, mobs) and a player one using
    geometry.player.armor.* plus the vanilla offset animation, selected by query.owner_identifier."""
    kind = cfg["kinds"][piece["kind"]]
    texture = f"{paths.armor_texture_dir}/{piece['layer']}"
    common = {
        "materials": {"default": "armor", "enchanted": "armor_enchanted"},
        "textures": {"default": texture, "enchanted": GLINT},
    }
    generic = {
        "format_version": cfg["attachable_format_version"],
        "minecraft:attachable": {
            "description": {
                "identifier": piece["identifier"],
                **common,
                "geometry": {"default": f"geometry.humanoid.armor.{piece['kind']}"},
                "scripts": {"parent_setup": kind["parent_setup"]},
                "render_controllers": ["controller.render.armor"],
            }
        },
    }
    player = {
        "format_version": cfg["attachable_format_version"],
        "minecraft:attachable": {
            "description": {
                "identifier": f"{piece['identifier']}.player",
                "item": {piece["identifier"]: "query.owner_identifier == 'minecraft:player'"},
                **common,
                "geometry": {"default": f"geometry.player.armor.{piece['kind']}"},
                "scripts": {"parent_setup": kind["parent_setup"], "animate": ["offset"]},
                "animations": {"offset": kind["animation"]},
                "render_controllers": ["controller.render.armor"],
            }
        },
    }
    return {f"{piece['id']}.json": generic, f"{piece['id']}.player.json": player}


def generate_json() -> None:
    cfg, paths = load_config()
    bp, rp = paths.bp, paths.rp
    # clear generated folders so removed pieces don't linger
    for d in (bp / "items", bp / "recipes", rp / "attachables"):
        if d.exists():
            for old in d.glob("*.json"):
                old.unlink()

    texture_data = {}
    lang = ["## GENERATED by tools/gen_json.py from tools/gear_config.json - do not edit by hand"]
    for piece in cfg["pieces"]:
        write_json(bp / "items" / f"{piece['id']}.json", item_json(cfg, piece))
        write_json(bp / "recipes" / f"{piece['id']}.json", recipe_json(cfg, piece))
        for name, data in attachables(cfg, paths, piece).items():
            write_json(rp / "attachables" / name, data)
        texture_data[texture_key(cfg, piece)] = {"textures": f"{paths.item_texture_dir}/{piece['id']}"}
        lang.append(f"item.{piece['identifier']}.name={piece['name']}")
    write_json(rp / "textures" / "item_texture.json", {
        "resource_pack_name": cfg["namespace"],
        "texture_name": "atlas.items",
        "texture_data": texture_data,
    })
    lang += [
        "",
        "## used by scripts/main.js via rawtext translate",
        "gear.set_bonus.on=§dAmethyst set bonus: §fResistance I",
        "gear.set_bonus.off=§7Amethyst set bonus lost",
        "gear.goggles.on=§dGeode Goggles: §fNight Vision",
        "gear.goggles.off=§7Geode Goggles removed",
    ]
    write_text(rp / "texts" / "en_US.lang", "\n".join(lang) + "\n")
    write_json(rp / "texts" / "languages.json", ["en_US"])
    n = len(cfg["pieces"])
    print(f"  {n} items + {n} recipes -> {rel(bp)}, {2 * n} attachables + item_texture.json + en_US.lang -> {rel(rp)}")


if __name__ == "__main__":
    try:
        generate_json()
    except BuildError as e:
        print(f"ERROR: {e}", file=sys.stderr)
        sys.exit(1)
